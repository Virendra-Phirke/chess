piece_position_scores = {
    "n": knight_scores,
    "b": bishop_scores,
    "r": rook_scores,
    "q": queen_scores,
    "p": pawn_scores
}

def evaluate_board(board):
    # Positive score = white advantage
    # Negative score = black advantage
    score = 0
    for r in range(8):
        for c in range(8):
            piece = board.grid[r][c]
            if piece:
                is_white = piece.color == "w"
                multiplier = 1 if is_white else -1
                
                score += piece_scores.get(piece.name.upper(), 0) * multiplier
                
                pos_table = piece_position_scores.get(piece.name, None)
                if pos_table:
                    pos_r = r if is_white else 7 - r
                    score += pos_table[pos_r][c] * multiplier
    return score
